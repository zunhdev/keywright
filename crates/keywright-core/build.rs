//! Embeds the keyboard support packs in `support-packs/` (tech spec §10).
//!
//! Each directory there is a pack. This script writes a list of every pack's files, each
//! with an `include_str!` of its contents, to `OUT_DIR`, and `src/support_packs.rs`
//! includes the list. So adding a pack needs no code: the next build picks it up, and the
//! pack's validation test checks it.
//!
//! Hidden files, such as `.DS_Store`, and each pack's `upstream/` directory are left out.
//! `upstream/` holds the files a pack's data comes from, which only its tests read.

#![forbid(unsafe_code)]
#![allow(
    clippy::print_stdout,
    reason = "Cargo reads a build script's instructions from its standard output"
)]

use std::env;
use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// The packs, relative to this crate.
const PACKS_DIR: &str = "../../support-packs";

/// A pack's source material, which isn't embedded.
const UPSTREAM_DIR: &str = "upstream";

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rerun-if-changed={PACKS_DIR}");

    let packs = Path::new(&env::var("CARGO_MANIFEST_DIR")?)
        .join(PACKS_DIR)
        .canonicalize()?;
    let mut code = String::from("// Generated by keywright-core's build script. Don't edit.\n&[\n");
    for pack in sorted_entries(&packs)? {
        if !pack.is_dir() {
            continue;
        }
        let name = file_name(&pack)?;
        writeln!(
            code,
            "    PackFiles {{\n        dir: {name:?},\n        files: &["
        )?;
        let mut files = Vec::new();
        collect_files(&pack, &pack, &mut files)?;
        for (path, absolute) in files {
            let absolute = absolute
                .to_str()
                .ok_or_else(|| format!("{} isn't UTF-8", absolute.display()))?;
            writeln!(code, "            ({path:?}, include_str!({absolute:?})),")?;
        }
        code.push_str("        ],\n    },\n");
    }
    code.push_str("]\n");

    fs::write(
        Path::new(&env::var("OUT_DIR")?).join("support_packs.rs"),
        code,
    )?;
    Ok(())
}

/// Adds the files under `dir` to `files`, as their path relative to `pack`, with `/`
/// between directories, and their absolute path.
fn collect_files(
    pack: &Path,
    dir: &Path,
    files: &mut Vec<(String, PathBuf)>,
) -> Result<(), Box<dyn Error>> {
    for entry in sorted_entries(dir)? {
        let name = file_name(&entry)?;
        if name.starts_with('.') || (dir == pack && name == UPSTREAM_DIR) {
            continue;
        }
        if entry.is_dir() {
            collect_files(pack, &entry, files)?;
        } else {
            let relative = entry
                .strip_prefix(pack)?
                .iter()
                .map(|part| part.to_str().ok_or("a file name isn't UTF-8"))
                .collect::<Result<Vec<_>, _>>()?
                .join("/");
            files.push((relative, entry));
        }
    }
    Ok(())
}

/// The entries of a directory, sorted, so the generated code is always the same.
fn sorted_entries(dir: &Path) -> Result<Vec<PathBuf>, Box<dyn Error>> {
    let mut entries = fs::read_dir(dir)?
        .map(|entry| entry.map(|entry| entry.path()))
        .collect::<Result<Vec<_>, _>>()?;
    entries.sort();
    Ok(entries)
}

fn file_name(path: &Path) -> Result<String, Box<dyn Error>> {
    Ok(path
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or_else(|| format!("{} has no UTF-8 name", path.display()))?
        .to_owned())
}
