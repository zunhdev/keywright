/**
 * TypeScript typings for CSS Modules: for each `Name.module.css`, a `Name.module.d.css.ts`
 * that names its classes, which TypeScript reads with `allowArbitraryExtensions`. A class
 * a component uses but the stylesheet doesn't have then fails `tsc`.
 */

import { transform } from "lightningcss";

/** The typings file for the CSS Module at `path`. */
export function typingsPath(path: string): string {
  return path.replace(/\.module\.css$/u, ".module.d.css.ts");
}

/** A class name as a property: quoted only if it isn't an identifier, as the formatter writes it. */
function key(name: string): string {
  return /^[$A-Z_a-z][\w$]*$/u.test(name) ? name : JSON.stringify(name);
}

/** The typings for a CSS Module, from its file name and text. */
export function typings(fileName: string, css: string): string {
  const { exports } = transform({
    filename: fileName,
    code: new TextEncoder().encode(css),
    cssModules: true,
  });
  const classes = Object.keys(exports ?? {}).toSorted();
  const lines = classes.map((name) => `  readonly ${key(name)}: string;`);
  return [
    `// The classes of ${fileName}, generated by \`mise run generate:css-types\`. Don't edit.`,
    "declare const classes: {",
    ...lines,
    "};",
    "export default classes;",
    "",
  ].join("\n");
}
