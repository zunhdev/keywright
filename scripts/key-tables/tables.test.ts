import { describe, expect, test } from "bun:test";

import type { DomCodeEntry } from "./chromium.ts";
import { zmk, zmkKeys } from "./sources.ts";
import { domCodesFile, hidUsagesFile, macKeyCodesFile, zmkNamesFile } from "./tables.ts";
import type { KeyName } from "./zmk.ts";

/** A key name from keys.h: its code is `[mods, page, id]`. */
const keyName = (
  name: string,
  [mods, page, id]: [number, number, number],
  description?: string,
  deprecated = false,
): KeyName => ({ name, code: { mods, page, id }, deprecated, description });

const names: KeyName[] = [
  keyName("B", [0, 0x07, 0x05], "Keyboard b and B"),
  keyName("A", [0, 0x07, 0x04], "Keyboard a and A"),
  keyName("QUOT", [0, 0x07, 0x34], `Keyboard ' and " (Quote)`, true),
  keyName("DQT", [0x02, 0x07, 0x34], `Keyboard " (Quote)`),
  keyName("C_MUTE", [0, 0x0c, 0xe2], "Consumer Mute"),
  keyName("SYS_PWR", [0, 0x01, 0x81], "System Power Down"),
];

const rows = (file: { contents: string }): string[] =>
  file.contents.split("\n").filter((line) => line.startsWith("("));

describe("hidUsagesFile", () => {
  test("names each usage once, sorted, without shifted names or other pages", () => {
    expect(rows(hidUsagesFile(names, [zmkKeys]))).toEqual([
      '(key(0x04), "Keyboard a and A"),',
      '(key(0x05), "Keyboard b and B"),',
      String.raw`(key(0x34), "Keyboard ' and \" (Quote)"),`,
      '(consumer(0xE2), "Consumer Mute"),',
    ]);
  });

  test("names the sources in its header", () => {
    const { contents } = hidUsagesFile(names, [zmkKeys]);
    expect(contents).toStartWith("// @generated by scripts/generate-key-tables.ts.");
    expect(contents).toContain(`ZMK v0.3.0, revision ${zmk.revision}`);
    expect(contents).toContain(zmk.fileUrl(zmkKeys.path));
  });

  test("throws when a usage has no description", () => {
    const undescribed = [keyName("B", [0, 0x07, 0x05])];
    expect(() => hidUsagesFile(undescribed, [zmkKeys])).toThrow("has no description");
  });
});

describe("zmkNamesFile", () => {
  test("keeps the order of keys.h, with modifiers and deprecation", () => {
    expect(rows(zmkNamesFile(names, [zmkKeys]))).toEqual([
      '("B", shortcut(Mods::NONE, key(0x05)), false),',
      '("A", shortcut(Mods::NONE, key(0x04)), false),',
      '("QUOT", shortcut(Mods::NONE, key(0x34)), true),',
      '("DQT", shortcut(Mods::LEFT_SHIFT, key(0x34)), false),',
      '("C_MUTE", shortcut(Mods::NONE, consumer(0xE2)), false),',
    ]);
  });

  test("writes several modifiers as bits", () => {
    const both = [keyName("B", [0x0a, 0x07, 0x05], "Keyboard b and B")];
    expect(rows(zmkNamesFile(both, [zmkKeys]))).toEqual([
      '("B", shortcut(Mods::from_bits(0x0A), key(0x05)), false),',
    ]);
  });

  test("refuses text that isn't printable ASCII", () => {
    const accented = [keyName("É", [0, 0x07, 0x05], "Keyboard b and B")];
    expect(() => zmkNamesFile(accented, [zmkKeys])).toThrow("not printable ASCII");
  });
});

const entries: DomCodeEntry[] = [
  { page: 0x00, id: 0x10, mac: undefined, code: "Hyper" },
  { page: 0x01, id: 0x97, mac: undefined, code: "Fn" },
  { page: 0x07, id: 0x04, mac: 0x00, code: "KeyA" },
  { page: 0x07, id: 0x80, mac: 0x48, code: "AudioVolumeUp" },
  { page: 0x07, id: 0xd7, mac: undefined, code: undefined },
  { page: 0x0c, id: 0xcd, mac: undefined, code: "MediaPlayPause" },
];

describe("domCodesFile", () => {
  test("keeps codes on the keyboard and consumer pages", () => {
    expect(rows(domCodesFile(entries, [zmkKeys]))).toEqual([
      '("KeyA", key(0x04)),',
      '("AudioVolumeUp", key(0x80)),',
      '("MediaPlayPause", consumer(0xCD)),',
    ]);
  });

  test("throws when a code appears twice", () => {
    const twice = [...entries, { page: 0x07, id: 0x05, mac: undefined, code: "KeyA" }];
    expect(() => domCodesFile(twice, [zmkKeys])).toThrow("KeyboardEvent.code KeyA");
  });
});

describe("macKeyCodesFile", () => {
  const virtualKeyCodes = new Map([
    [0x00, "kVK_ANSI_A"],
    [0x48, "kVK_VolumeUp"],
    [0x3f, "kVK_Function"],
  ]);

  test("names each code's constant", () => {
    expect(rows(macKeyCodesFile(entries, virtualKeyCodes, [zmkKeys]))).toEqual([
      "(key(0x04), 0x00), // kVK_ANSI_A",
      "(key(0x80), 0x48), // kVK_VolumeUp",
    ]);
  });

  test("fails when Chromium uses a code that Events.h doesn't define", () => {
    const fewer = new Map([...virtualKeyCodes].filter(([code]) => code !== 0x48));
    expect(() => macKeyCodesFile(entries, fewer, [zmkKeys])).toThrow(
      "Chromium maps a key to 0x48, which Events.h doesn't define",
    );
  });

  test("fails when Events.h defines a code that no usage maps to", () => {
    const more = new Map([...virtualKeyCodes, [0x0a, "kVK_ISO_Section"]]);
    expect(() => macKeyCodesFile(entries, more, [zmkKeys])).toThrow(
      "Events.h defines kVK_ISO_Section (0x0A), which no usage maps to",
    );
  });

  test("throws when a code appears twice", () => {
    const twice = [...entries, { page: 0x07, id: 0x05, mac: 0x00, code: "KeyB" }];
    expect(() => macKeyCodesFile(twice, virtualKeyCodes, [zmkKeys])).toThrow("macOS key code 0");
  });
});
